import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const sourceNames = [
  "utils/constants.js",
  "utils/permissions.js",
  "utils/alert-labels.js",
  "utils/navigation.js",
  "api/transport.js",
  "utils/escaping.js",
  "utils/table-preferences.js",
  "utils/formatting.js",
  "utils/translations.js",
  "api/alert-manager-api.js",
  "components/duration-field.js",
  "components/alert-table.js",
  "components/config-backups.js",
  "components/configuration-drawer.js",
  "components/configuration-yaml.js",
  "components/notification-profiles.js",
  "components/rule-editor.js",
  "views/overview.js",
  "views/history.js",
  "views/coherence.js",
  "views/rules.js",
  "views/automatic.js",
  "views/settings.js",
  "styles/base-styles.js",
  "styles/table-styles.js",
  "styles/settings-styles.js",
  "styles/rule-editor-styles.js",
  "styles/state-styles.js",
  "styles/responsive-styles.js",
  "styles/panel-styles.js",
  "alert-manager-panel.js",
];

const stripModuleSyntax = (source) => source
  .replace(/^import\s+["'][^"']+["'];\n/gm, "")
  .replace(/^import[\s\S]*?from\s+["'][^"']+["'](?: with \{[^}]+\})?;\n/gm, "")
  .replace(/^export (async function|function|class|const) /gm, "$1 ")
  .replace(/^export \{[^}]+\};\s*$/gm, "")
  .trim();

const dashboardNames = [
  "dashboard/frontend-ready.js",
  "utils/constants.js", "utils/escaping.js", "utils/alert-labels.js",
  "utils/navigation.js", "utils/formatting.js", "api/transport.js", "api/dashboard.js",
  "dashboard/translations.js", "dashboard/groups.js", "dashboard/editor.js",
  "styles/dashboard-styles.js", "dashboard/card.js",
];

for (const [bundleName, names] of [
  ["alert-manager-panel", sourceNames], ["alert-manager-card", dashboardNames],
]) {
  const modules = [];
  if (bundleName === "alert-manager-card") {
    for (const [language, variable] of [["en", "englishDashboardSource"], ["fr", "frenchDashboardSource"]]) {
      const translation = JSON.parse(await readFile(new URL(
        `../custom_components/alert_manager/translations/${language}.json`, import.meta.url,
      ), "utf8"));
      const config_panel = Object.fromEntries(["dashboard", "conditions", "duration", "operators", "packs"]
        .map((key) => [key, translation.config_panel[key]]));
      config_panel.coherence = { title: translation.config_panel.coherence.title };
      modules.push(`const ${variable} = ${JSON.stringify({ config_panel })};`);
    }
  }
  for (const filename of names) {
    const source = await readFile(
      new URL(`../frontend-src/${filename}`, import.meta.url),
      "utf8",
    );
    modules.push(`// Source: frontend-src/${filename}\n${stripModuleSyntax(source)}`);
  }

  const bundle = `${[
    "// Generated by scripts/build-frontend.mjs. Do not edit directly.",
    ...modules,
  ].join("\n\n").trimEnd()}\n`;
  if (/^\s*(?:import|export)\s/m.test(bundle)) {
    throw new Error("The distributed frontend must be a standalone script");
  }

  const destination = new URL(
    `../custom_components/alert_manager/frontend/${bundleName}.js`,
    import.meta.url,
  );
  await mkdir(dirname(destination.pathname), { recursive: true });
  await writeFile(destination, bundle);

  const result = spawnSync(process.execPath, ["--check", destination.pathname], {
    encoding: "utf8",
  });
  if (result.status !== 0) {
    process.stderr.write(result.stderr);
    process.exit(result.status ?? 1);
  }

  console.log(`Built standalone ${bundleName}.js from responsibility modules`);
}
