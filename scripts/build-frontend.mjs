import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const sourceNames = [
  "utils/constants.js",
  "utils/escaping.js",
  "utils/table-preferences.js",
  "utils/formatting.js",
  "utils/translations.js",
  "api/alert-manager-api.js",
  "components/alert-table.js",
  "components/config-backups.js",
  "components/configuration-drawer.js",
  "components/rule-editor.js",
  "views/overview.js",
  "views/history.js",
  "views/coherence.js",
  "views/rules.js",
  "views/automatic.js",
  "views/settings.js",
  "styles/base-styles.js",
  "styles/table-styles.js",
  "styles/settings-styles.js",
  "styles/rule-editor-styles.js",
  "styles/state-styles.js",
  "styles/responsive-styles.js",
  "styles/panel-styles.js",
  "alert-manager-panel.js",
];

const stripModuleSyntax = (source) => source
  .replace(/^import[\s\S]*?from\s+["'][^"']+["'];\n/gm, "")
  .replace(/^export (async function|function|class|const) /gm, "$1 ")
  .replace(/^export \{[^}]+\};\s*$/gm, "")
  .trim();

const modules = [];
for (const filename of sourceNames) {
  const source = await readFile(
    new URL(`../frontend-src/${filename}`, import.meta.url),
    "utf8",
  );
  modules.push(`// Source: frontend-src/${filename}\n${stripModuleSyntax(source)}`);
}

const bundle = `${[
  "// Generated by scripts/build-frontend.mjs. Do not edit directly.",
  ...modules,
].join("\n\n").trimEnd()}\n`;
if (/^\s*(?:import|export)\s/m.test(bundle)) {
  throw new Error("The distributed frontend must be a standalone script");
}

const destination = new URL(
  "../custom_components/alert_manager/frontend/alert-manager-panel.js",
  import.meta.url,
);
await mkdir(dirname(destination.pathname), { recursive: true });
await writeFile(destination, bundle);

const result = spawnSync(process.execPath, ["--check", destination.pathname], {
  encoding: "utf8",
});
if (result.status !== 0) {
  process.stderr.write(result.stderr);
  process.exit(result.status ?? 1);
}

console.log("Built standalone alert-manager-panel.js from responsibility modules");
